#!/usr/bin/env bash
# Builds a readable changelog section from the commits since the previous tag.
#   ./scripts/changelog.sh            -> prints markdown for the latest range
#   ./scripts/changelog.sh v1.5.20    -> since that tag
set -euo pipefail
cd "$(dirname "$0")/.."
SINCE="${1:-$(git describe --tags --abbrev=0 2>/dev/null || git rev-list --max-parents=0 HEAD | head -1)}"
echo "## Changes since $SINCE"
echo
git log --no-merges --pretty=format:'- %s' "$SINCE"..HEAD | sed 's/^- v[0-9.]*: /- /'
echo
echo
echo "_Generated by scripts/changelog.sh_"
